#!/bin/sh
# ══════════════════════════════════════════════════════════════════════
#  installa.sh — scrive i sorgenti del progetto in questa cartella.
#
#  I file sono racchiusi qui sotto in base64: solo lettere e numeri,
#  quindi il contenuto non si rovina passando per browser, GitHub o
#  editor che cambiano i fine riga. Prima di scrivere niente, lo
#  script controlla l'impronta: se il file è arrivato monco, te lo
#  dice invece di lasciare a metà.
#
#  Uso:   bash installa.sh
# ══════════════════════════════════════════════════════════════════════
set -e

ATTESA=d572682217276dd599306935240b2a5c2647a9e38ca2906451d417c1d992f266
INIZIO=$(grep -n '^__DATI__$' "$0" | head -1 | cut -d: -f1)

estrai() { tail -n +$((INIZIO + 1)) "$0" | tr -d '\r' | base64 -d 2>/dev/null; }

echo "controllo il file…"
OTTENUTA=$(estrai | sha256sum | cut -d' ' -f1)

if [ "$OTTENUTA" != "$ATTESA" ]; then
  echo
  echo "  Il file è arrivato danneggiato: non lo apro."
  echo "  attesa   $ATTESA"
  echo "  ottenuta $OTTENUTA"
  echo
  echo "  Riscaricalo e ricaricalo su GitHub senza aprirlo in un editor."
  exit 1
fi

echo "impronta corretta. Scrivo i sorgenti…"
estrai | tar xzf -

echo
if command -v node >/dev/null 2>&1; then
  echo "genero citta-core.html…"
  node build.js
else
  echo "node non ancora installato: quando lo sarà, lancia  node build.js"
fi

echo
echo "fatto. File presenti:"
ls -1
exit 0

